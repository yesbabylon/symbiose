namespace infra\server;

use equal\orm\Model;

class AlertTrigger extends Model {

    public static function getColumns(): array {
        return [

            'name' => [
                'type'              => 'computed',
                'result_type'       => 'string',
                'relation'          => ['message_model_id' => 'label'],
                'description'       => 'Display name of the alert trigger.',
                'store'             => true,
                'instant'           => true,
                'multilang'         => true
            ],

            'object_class' => [
                'type'              => 'string',
                'usage'             => 'text/plain:128',
                'description'       => "Class of entity this entry is related to.",
                'help'              => "Is a template if left empty.",
                'readonly'          => true
            ],

            'object_id' => [
                'type'              => 'integer',
                'description'       => "Identifier of the targeted object (of given class).",
                'help'              => "Is a template if left empty.",
                'readonly'          => true
            ],

            'scope' => [
                'type'              => 'string',
                'description'       => "The scope of data that the alert trigger needs.",
                'selection'         => [
                    'instant',
                    'state',
                    'config',
                    'none'
                ],
                'required'          => true
            ],

            'repetition' => [
                'type'              => 'integer',
                'description'       => "Number of repetitions needed for the alert to be triggered.",
                'help'              => "If repetition is 2, then the trigger must match twice in a row.",
                'default'           => 1
            ],

            'checks_ids' => [
                'type'              => 'many2many',
                'foreign_object'    => 'infra\server\Check',
                'foreign_field'     => 'alert_triggers_ids',
                'rel_table'         => 'infra_check_rel_alert_trigger',
                'rel_foreign_key'   => 'check_id',
                'rel_local_key'     => 'alert_trigger_id',
                'description'       => "Checks used to trigger the alert.",
                'domain'            => [
                    ['object_class', '=', 'object.object_class'],
                    ['object_id', '=', 'object.object_id'],
                    ['scope', '=', 'object.scope']
                ]
            ],

            'user_id' => [
                'type'              => 'many2one',
                'foreign_object'    => 'core\User',
                'description'       => 'User concerned by the alert, if any.'
            ],

            'group_id' => [
                'type'              => 'many2one',
                'foreign_object'    => 'core\Group',
                'description'       => 'Group concerned by the alert, if any.'
            ],

            'severity' => [
                'type'              => 'string',
                'description'       => "Severity of the created alerts.",
                'selection'         => [
                    'notice',
                    'warning',
                    'important',
                    'urgent'
                ],
                'default'           => 'warning'
            ],

            'message_model_id' => [
                'type'              => 'many2one',
                'foreign_object'    => 'core\alert\MessageModel',
                'description'       => "Model of message to use for the alert generation.",
                'required'          => true,
                'dependents'        => ['name']
            ],

            'alert_messages_ids' => [
                'type'              => 'one2many',
                'foreign_object'    => 'core\alert\Message',
                'foreign_field'     => 'object_id',
                'domain'            => ['object_class', '=', 'infra\server\AlertTrigger'],
                'description'       => "The alert messages that were generated by this alert trigger."
            ]

        ];
    }

    public static function getConstraints(): array {
        return [
            'repetition' => [
                'repetition_min_is_one' => [
                    'message'       => 'Min repetition is 1',
                    'function'      => function($repetition, $values) {
                        return $repetition > 0;
                    }
                ]
            ]
        ];
    }
}
